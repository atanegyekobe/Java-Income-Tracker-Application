    private void jButton14ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton14ActionPerformed

        SessionManager sessionManager = SessionManager.getInstance();
        int userId = sessionManager.getUserId();

        // Get the selected row index
        int selectedRow = jTable3.getSelectedRow();

        if (selectedRow == -1) {
            // No row is selected
            JOptionPane.showMessageDialog(null, "Please select a row to delete.");
            return;
        }

        // Retrieve the column index of the expense_id
        int expenseIdColumnIndex = -1;
        DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
        for (int i = 0; i < model.getColumnCount(); i++) {
            if ("expense_id".equals(model.getColumnName(i))) {
                expenseIdColumnIndex = i;
                break;
            }
        }

        if (expenseIdColumnIndex == -1) {
            // expense_id column not found
            JOptionPane.showMessageDialog(null, "Column 'expense_id' not found.");
            return;
        }

        // Retrieve data from the selected row
        String expenseIdStr = model.getValueAt(selectedRow, expenseIdColumnIndex).toString();
        int expenseId = Integer.parseInt(expenseIdStr);  // Assuming expense_id is an integer

        // SQL query to delete the row from the expenses table
        String sql = "DELETE FROM expenses WHERE user_id = ? AND expense_id = ?";

        MyDataConnect dbConnect = new MyDataConnect();
        try (Connection connection = dbConnect.getConnection();
            PreparedStatement pstmt = connection.prepareStatement(sql)) {
            // Set parameters for user_id and expense_id
            pstmt.setInt(1, userId);
            pstmt.setInt(2, expenseId);

            // Execute the delete query
            pstmt.executeUpdate();

            // Remove the selected row from the jTable3
            model.removeRow(selectedRow);
            ActivityLogger.logActivity(userId, "Transactions", "Payment made successfully.");
            // Show confirmation message
            JOptionPane.showMessageDialog(null, "Payment made successfully.");
        } catch (SQLException e) {
            e.printStackTrace();
            // Handle potential SQL exceptions
            JOptionPane.showMessageDialog(null, "Please check your Expenses: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton14ActionPerformed

