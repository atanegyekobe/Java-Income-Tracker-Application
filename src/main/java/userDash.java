    private void jButton12ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton12ActionPerformed
        // Retrieve user_id from SessionManager
        SessionManager sessionManager = SessionManager.getInstance();
        int userId = sessionManager.getUserId();

        // Get the selected source from jComboBox6
        String selectedSource = (String) jComboBox6.getSelectedItem();

        // SQL query to sum amounts for the selected source
        String sql = "SELECT SUM(amount) AS total_amount FROM income WHERE user_id = ? AND source = ?";

        MyDataConnect dbConnect = new MyDataConnect();
        try (Connection connection = dbConnect.getConnection();
            PreparedStatement pstmt = connection.prepareStatement(sql)) {
            // Set parameters for user_id and source
            pstmt.setInt(1, userId);
            pstmt.setString(2, selectedSource);

            // Execute the query
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    double totalAmount = rs.getDouble("total_amount");

                    // Display the total amount on jLabel35
                    jLabel36.setText(String.format("'%s': %.2f", selectedSource, totalAmount));
                } else {
                    // No matching records found
                    jLabel36.setText("No records found for the selected source.");
                }
            }
        } catch (SQLException e) {
            e.printStackTrace();
            // Handle potential SQL exceptions
        }
    }//GEN-LAST:event_jButton12ActionPerformed

