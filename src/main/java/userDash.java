        int userId = sessionManager.getUserId();

        // Get start and end dates from jDateChooser9 and jDateChooser10
        java.util.Date startDate = jDateChooser9.getDate();
        java.util.Date endDate = jDateChooser10.getDate(); // Assuming jDateChooser10 is used for end date

