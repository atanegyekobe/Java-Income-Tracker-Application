    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        try {
            // Retrieve user inputs
            java.util.Date startDate = jDateChooser3.getDate();
            java.util.Date endDate = jDateChooser4.getDate();
            String monthlyIncomeText = jTextField3.getText();
            String notes = jTextArea1.getText();

            // Validate inputs
            if (startDate == null || endDate == null || monthlyIncomeText.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all required fields.");
                return;
            }

            // Format dates
            java.sql.Date sqlStartDate = new java.sql.Date(startDate.getTime());
            java.sql.Date sqlEndDate = new java.sql.Date(endDate.getTime());
            double monthlyIncome = Double.parseDouble(monthlyIncomeText);

            // Get user ID from SessionManager
            int userId = SessionManager.getInstance().getUserId();

            // Prepare SQL statements
            String getTotalIncomeSql = "SELECT SUM(amount) AS total_income FROM income WHERE user_id = ?";
            String updateTotalIncomeSql = "UPDATE income SET amount = amount - ? WHERE user_id = ?";
            String insertBudgetSql = "INSERT INTO budget (user_id, start_date, end_date, monthly_income, notes) VALUES (?, ?, ?, ?, ?)";

            MyDataConnect dbConnect = new MyDataConnect();

            try (Connection connection = dbConnect.getConnection()) {
                // Fetch current total income
                double totalIncome = 0.0;
                try (PreparedStatement pstmt = connection.prepareStatement(getTotalIncomeSql)) {
                    pstmt.setInt(1, userId);
                    ResultSet rs = pstmt.executeQuery();
                    if (rs.next()) {
                        totalIncome = rs.getDouble("total_income");
                    }
                }

                // Validate total income
                if (totalIncome < monthlyIncome) {
                    JOptionPane.showMessageDialog(this, "Insufficient total income to set this budget.");
                    return;
                }

                // Update total income
                try (PreparedStatement pstmt = connection.prepareStatement(updateTotalIncomeSql)) {
                    pstmt.setDouble(1, monthlyIncome);
                    pstmt.setInt(2, userId);
                    pstmt.executeUpdate();
                }

                // Insert budget details
                try (PreparedStatement pstmt = connection.prepareStatement(insertBudgetSql)) {
                    pstmt.setInt(1, userId);
                    pstmt.setDate(2, sqlStartDate);
                    pstmt.setDate(3, sqlEndDate);
                    pstmt.setDouble(4, monthlyIncome);
                    pstmt.setString(5, notes);
                    pstmt.executeUpdate();
                    ActivityLogger.logActivity(userId, "User saves Budget", "Budget saved successfully.");
                }

                // Confirm success
                JOptionPane.showMessageDialog(this, "Budget saved successfully.");

                // Clear the input fields
                jDateChooser3.setDate(null);
                jDateChooser4.setDate(null);
                jTextField3.setText("");
                jTextArea1.setText("");

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
                ex.printStackTrace();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Invalid input. Please enter valid numbers.");
        }
    }//GEN-LAST:event_jButton7ActionPerformed

