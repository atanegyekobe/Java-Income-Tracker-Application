    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // Get the selected row index from jTable1
        int selectedRow = jTable1.getSelectedRow();

        if (selectedRow == -1) {
            // No row is selected
            JOptionPane.showMessageDialog(null, "Please select a row to delete.");
            return;
        }

        // Retrieve the user_id from the selected row
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        int userId = (int) model.getValueAt(selectedRow, 0); // Assuming user_id is in the first column

        // SQL query to delete the row from the users table
        String sql = "DELETE FROM users WHERE user_id = ?";

        MyDataConnect dbConnect = new MyDataConnect();
        try (Connection connection = dbConnect.getConnection();
            PreparedStatement pstmt = connection.prepareStatement(sql)) {
            // Set the user_id parameter for the SQL query
            pstmt.setInt(1, userId);

            // Execute the delete query
            int rowsAffected = pstmt.executeUpdate();

            // Check if the row was successfully deleted
            if (rowsAffected > 0) {
                // Remove the selected row from the table model
                model.removeRow(selectedRow);

                // Show a confirmation message
                JOptionPane.showMessageDialog(null, "User deleted successfully.");
            } else {
                JOptionPane.showMessageDialog(null, "Failed to delete user.");
            }
        } catch (SQLException e) {
            e.printStackTrace();
            // Handle potential SQL exceptions
            JOptionPane.showMessageDialog(null, "Error deleting user: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

