    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
      // Fetch data from budget table and display in jTable4
    String sql = "SELECT * FROM budget";
    MyDataConnect dbConnect = new MyDataConnect();

    try (Connection connection = dbConnect.getConnection();
         PreparedStatement pstmt = connection.prepareStatement(sql);
         ResultSet rs = pstmt.executeQuery()) {

        // Get metadata to create table model
        ResultSetMetaData rsmd = rs.getMetaData();
        int columnCount = rsmd.getColumnCount();

        // Create table model and set column names
        DefaultTableModel tableModel = new DefaultTableModel();
        for (int i = 1; i <= columnCount; i++) {
            tableModel.addColumn(rsmd.getColumnName(i));
        }

        // Add rows to table model
        while (rs.next()) {
            Object[] rowData = new Object[columnCount];
            for (int i = 1; i <= columnCount; i++) {
                rowData[i - 1] = rs.getObject(i);
            }
            tableModel.addRow(rowData);
        }

        // Set model to jTable4
        jTable4.setModel(tableModel);

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        ex.printStackTrace();
    }
    }//GEN-LAST:event_jButton7ActionPerformed

    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        // Retrieve email from jTextField8
    String email = jTextField8.getText().trim();

    // Validate email input
    if (email.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please enter an email.");
        return;
    }

    // Initialize database connection
    MyDataConnect dbConnect = new MyDataConnect();
    Connection connection = null;
    PreparedStatement pstmt = null;
    ResultSet rs = null;

    try {
        connection = dbConnect.getConnection();

        // Query to get user_id from users table
        String userQuery = "SELECT user_id FROM users WHERE email = ?";
        pstmt = connection.prepareStatement(userQuery);
        pstmt.setString(1, email);
        rs = pstmt.executeQuery();

        if (rs.next()) {
            int userId = rs.getInt("user_id");

            // Query to fetch budget details using user_id
            String budgetQuery = "SELECT * FROM budget WHERE user_id = ?";
            pstmt = connection.prepareStatement(budgetQuery);
            pstmt.setInt(1, userId);
            rs = pstmt.executeQuery();

            // Get metadata to create table model
            ResultSetMetaData rsmd = rs.getMetaData();
            int columnCount = rsmd.getColumnCount();

            // Create table model and set column names
            DefaultTableModel tableModel = new DefaultTableModel();
            for (int i = 1; i <= columnCount; i++) {
                tableModel.addColumn(rsmd.getColumnName(i));
            }

            // Add rows to table model
            while (rs.next()) {
                Object[] rowData = new Object[columnCount];
                for (int i = 1; i <= columnCount; i++) {
                    rowData[i - 1] = rs.getObject(i);
                }
                tableModel.addRow(rowData);
            }

            // Set model to jTable4
            jTable4.setModel(tableModel);

        } else {
            JOptionPane.showMessageDialog(this, "No user found with the provided email.");
        }

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        ex.printStackTrace();
    } finally {
        try {
            if (rs != null) rs.close();
            if (pstmt != null) pstmt.close();
            if (connection != null) connection.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    }//GEN-LAST:event_jButton8ActionPerformed

