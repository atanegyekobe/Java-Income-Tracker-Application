    private void jTabbedPane1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTabbedPane1MouseClicked
        //activity
        DefaultTableModel model = new DefaultTableModel(new String[]{"User ID", "Activity", "Timestamp", "Description"}, 0);
        String sql = "SELECT user_id, activity, timestamp, details FROM user_activity_logs";

        MyDataConnect dbConnect = new MyDataConnect();
        try (Connection connection = dbConnect.getConnection();
            Statement stmt = connection.createStatement();
            ResultSet rs = stmt.executeQuery(sql)) {

            while (rs.next()) {
                int userId = rs.getInt("user_id");
                String activity = rs.getString("activity");
                Timestamp timestamp = rs.getTimestamp("timestamp");
                String details = rs.getString("details");

                model.addRow(new Object[]{userId, activity, timestamp, details});
            }
            jTable2.setModel(model);
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jTabbedPane1MouseClicked

