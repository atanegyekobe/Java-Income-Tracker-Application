    private void jLabel6MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel6MouseClicked
        // SQL query to retrieve all fields from the users table
        String sql = "SELECT * FROM users";

        MyDataConnect dbConnect = new MyDataConnect();
        try (Connection connection = dbConnect.getConnection();
            Statement stmt = connection.createStatement();
            ResultSet rs = stmt.executeQuery(sql)) {

            // Get the table model
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows

            // Define column names (matching the users table schema)
            String[] columnNames = {"user_id", "username", "password", "email", "full_name", "sex", "phone_number"};
            model.setColumnIdentifiers(columnNames);

            // Populate the table with result set data
            while (rs.next()) {
                Object[] row = new Object[columnNames.length];
                row[0] = rs.getInt("user_id");
                row[1] = rs.getString("username");
                row[2] = rs.getString("password");
                row[3] = rs.getString("email");
                row[4] = rs.getString("full_name");
                row[5] = rs.getString("sex");
                row[6] = rs.getString("phone_number");
                model.addRow(row);
            }
        } catch (SQLException e) {
            e.printStackTrace();
            // Handle potential SQL exceptions
            JOptionPane.showMessageDialog(null, "Error retrieving user data: " + e.getMessage());
        }
    }//GEN-LAST:event_jLabel6MouseClicked

